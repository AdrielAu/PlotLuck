// Geographic confirmation uses the shipped catalogue and real scoring, without a model download.
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { test } from "node:test";
import { answerQuestions, newPage, openSite } from "./site.mjs";

test("London requires a labelled boundary choice and retains confirmed results until comparison", async (t) => {
  const { browser, url } = await openSite(t);
  const page = await newPage(browser);
  const requests = [];
  page.on("request", request => requests.push(request.url() + (request.postData() ?? "")));
  await page.goto(url);
  await page.locator('#answer[aria-busy="false"]').waitFor();
  await answerQuestions(page, ["London", "Thai", "", "", "", ""]);
  const compare = page.getByRole("button", { name: "Compare districts", exact: true });
  const intended = page.getByLabel("Intended place", { exact: true });
  const labels = await intended.locator("option").allTextContents();
  assert.ok(labels.includes("Greater London (region, England)"));
  assert.ok(labels.includes("City of London (city, England)"));
  assert.equal(await intended.inputValue(), "");
  await compare.click();
  assert.match(await page.getByRole("alert").innerText(), /Choose the intended place/);
  assert.equal(await intended.evaluate(el => el === document.activeElement), true);
  assert.equal(await page.locator("#results-screen").isVisible(), false);
  await intended.selectOption({ label: "City of London (city, England)" });
  assert.match(await page.locator("#draft-area-help").innerText(), /scores describe whole districts/);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await mkdir(".taste-skill", { recursive: true });
  await page.screenshot({ path: ".taste-skill/117-review-narrow.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: ".taste-skill/117-review-desktop.png", fullPage: true });
  await compare.focus();
  await page.keyboard.press("Enter");
  await page.locator("#results-screen").waitFor();
  assert.equal(await page.locator("#results-heading").innerText(), "Thai · City of London (city, England)");
  const slider = page.getByRole("slider", { name: "Score threshold", exact: true });
  await slider.evaluate(el => { el.value = el.min; el.dispatchEvent(new Event("input", { bubbles: true })); });
  assert.match(await page.locator("#count").innerText(), /^17 of 17 districts/);
  const cityCodes = await page.locator(".district-code").allInnerTexts();
  assert.ok(cityCodes.every(code => code.startsWith("EC")));
  await page.getByRole("button", { name: "Change answers", exact: true }).click();
  await answerQuestions(page, ["Greater London", "Thai", "", "", "", ""]);
  await compare.click();
  await page.locator("#results-screen").waitFor();
  await slider.evaluate(el => { el.value = el.min; el.dispatchEvent(new Event("input", { bubbles: true })); });
  assert.ok(await page.locator("#ranked li").count() > 17);
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
  assert.deepEqual(requests.filter(request => /London|Thai/.test(request)), []);
  assert.deepEqual(page.errors, []);
});

test("unknown names and empty boundaries never become England", async (t) => {
  const { browser, url } = await openSite(t);
  const page = await newPage(browser);
  await page.goto(url);
  await page.locator('#answer[aria-busy="false"]').waitFor();
  await answerQuestions(page, ["Hugh Town", "Thai", "", "", "", ""]);
  const intended = page.getByLabel("Intended place", { exact: true });
  if (!await intended.inputValue()) await intended.selectOption({ index: 1 });
  const compare = page.getByRole("button", { name: "Compare districts", exact: true });
  await compare.click();
  assert.match(await page.getByRole("alert").innerText(), /No district centroid/);
  const area = page.getByLabel("Search area", { exact: true });
  await area.fill("London except Camden");
  await compare.click();
  assert.match(await page.getByRole("alert").innerText(), /area exclusions need correcting/);
  assert.equal(await page.locator("#results-screen").isVisible(), false);
  await area.fill("");
  await compare.click();
  assert.deepEqual(page.errors, []);
  assert.equal(await page.locator("#review-error").isVisible(), false, await page.locator("#review-error").innerText());
  await page.locator("#results-screen").waitFor();
  assert.equal(await page.locator("#results-heading").innerText(), "Thai · England");
  assert.deepEqual(page.errors, []);
});
